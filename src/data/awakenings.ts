// Auteur : agent Game design. Valeurs de départ, à équilibrer (docs/equilibrage.md).
//
// Même convention de paramètres que src/data/talents.ts :
// - suffixe `Add` : ajouté au paramètre de base de `ability.params` (src/data/units.ts) ;
// - suffixe `Mul` : multiplicateur (clés génériques damageMul, attackSpeedMul, bossDamageMul…) ;
// - sans suffixe : nouvelle mécanique, valeur directe (`…Bonus` = fraction ajoutée).
// Clés propres aux passifs :
//   ultimateUsesPerWave / ultimateUsesPerGame / ultimateEvery (s)  fréquence d'un effet ultime
//   auraGlobal = 1    l'aura de l'unité touche tout le plateau
//   bossSlow          ralentissement appliqué aux boss (fraction)
// Les gains d'attaque et de vitesse de chaque étoile (+6 % / +4 % par étoile) ne sont pas ici :
// le moteur les calcule à partir de `PlayerSetup.awakening`.

import type { AwakeningPassiveDef, UnitId } from './types';

type P = Record<string, number>;
type Row = [string, string, P];

function u(unit: UnitId, s2: Row, s4: Row, s6: Row, s8: Row, s10: Row): AwakeningPassiveDef[] {
  const rows: [2 | 4 | 6 | 8 | 10, Row][] = [[2, s2], [4, s4], [6, s6], [8, s8], [10, s10]];
  return rows.map(([star, [name, description, params]]) => ({ unit, star, name, description, params }));
}

