/** Les 6 talents d'une unité, triés par palier puis option. */
export function talentsFor(unit: UnitId): TalentDef[] {
  return TALENTS.filter((t) => t.unit === unit).sort((a, b) => a.tier - b.tier || a.option.localeCompare(b.option));
}

